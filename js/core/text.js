// Нормализация текста для поиска: регистр, ё, казахские буквы, типы улиц.

const KK = { 'ә': 'а', 'ғ': 'г', 'қ': 'к', 'ң': 'н', 'ө': 'о', 'ұ': 'у', 'ү': 'у', 'һ': 'х', 'і': 'и', 'ё': 'е', 'й': 'и' };

/** Нижний регистр, казахские буквы → русские, без знаков препинания. */
export function norm(s) {
  return String(s || '').toLowerCase()
    .replace(/[әғқңөұүһіёй]/g, c => KK[c])
    .replace(/[«»"'`’.,;:!?()]/g, ' ')
    .replace(/[-–—]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Слова-типы улиц и мест не участвуют в совпадении: «Кенесары» = «улица Кенесары» = «Кенесары көшесі».
export const STREET_WORDS = new Set([
  'улица', 'ул', 'кошеси', 'кошесi', 'проспект', 'пр', 'просп', 'дангылы', 'переулок', 'пер', 'туиык', 'шоссе', 'тас', 'жолы',
  'бульвар', 'булвар', 'б р', 'площадь', 'пл', 'аланы', 'микрораион', 'мкр', 'шагын', 'ауданы', 'набережная', 'жагалауы',
  'тупик', 'проезд', 'откели', 'тракт', 'аллея', 'гулзар', 'жилмассив', 'жм', 'квартал', 'street', 'avenue', 'st', 'ave', 'көшесі',
  'раион', 'district'
]);

export function tokens(s) { return norm(s).split(' ').filter(Boolean); }

/** Значимые слова названия (без типов улиц). Если остались только типы — берём все. */
export function nameTokens(s) {
  const t = tokens(s);
  const meaningful = t.filter(w => !STREET_WORDS.has(w));
  return meaningful.length ? meaningful : t;
}

/** Номер дома для сравнения: «40/2» → «40/2», «40 а» → «40а». */
export const normHouse = (s) => norm(s).replace(/\s+/g, '').replace(/\\/g, '/');

export const hasDigit = (s) => /\d/.test(s);
