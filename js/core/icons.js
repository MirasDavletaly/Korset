const pathCache = new Map();
/** Рисует иконку на canvas: (cx, cy) — центр, size — размер в пикселях. */
export function drawIcon(ctx, name, cx, cy, size, color, lineWidth = 2.2) {
  let paths = pathCache.get(name);
  if (!paths) { paths = (ICONS[name] || ICONS.pin).map(d => new Path2D(d)); pathCache.set(name, paths); }
  const k = size / 24;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(k, k);
  ctx.strokeStyle = color;
  ctx.lineWidth = lineWidth;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  for (const p of paths) ctx.stroke(p);
  ctx.restore();
}
